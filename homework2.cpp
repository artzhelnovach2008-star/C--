#include <iostream>

using namespace std;

// 1. Функция, которая выводит в консоль каждый бит числа (от старших к младшим)
void printBits(int n) {
    // Определяем количество бит в типе int (обычно 32)
    int size = sizeof(int) * 8;
    cout << "Число " << n << " в двоичном виде: ";
    for (int i = size - 1; i >= 0; i--) {
        // Сдвигаем бит на i позиций вправо и проверяем с помощью побитового И (& 1)
        int bit = (n >> i) & 1;
        cout << bit;
        if (i % 4 == 0) cout << " "; // для читаемости разбиваем по 4 бита
    }
    cout << endl;
}

// 2. Проверка, является ли число парным или непарным с помощью побитовых операций
bool isEven(int n) {
    // У непарных чисел младший бит всегда равен 1. 
    // Если (n & 1) == 0, то число парное.
    return (n & 1) == 0;
}

// 3. Функция, которая очищает (устанавливает в 0) бит под заданным индексом
int clearBit(int n, int index) {
    // Создаем маску с нулем на месте индекса и единиц в остальных местах
    int mask = ~(1 << index);
    return n & mask;
}

// 4. Функция, которая устанавливает бит под заданным индексом в 1
int setBit(int n, int index) {
    // Создаем маску с единицей на нужном месте
    int mask = 1 << index;
    return n | mask;
}

// 5. Функция, которая инвертирует бит под заданным индексом (0 -> 1, 1 -> 0)
int toggleBit(int n, int index) {
    int mask = 1 << index;
    return n ^ mask; // операция XOR инвертирует бит
}

// 6. Функция, которая подсчитывает количество единичных и нулевых битов в числе
void countBits(int n) {
    int ones = 0;
    int zeros = 0;
    int size = sizeof(int) * 8;
    
    for (int i = 0; i < size; i++) {
        if ((n >> i) & 1) {
            ones++;
        } else {
            zeros++;
        }
    }
    cout << "Кількість одиничних бітів: " << ones << endl;
    cout << "Кількість нульових бітів: " << zeros << endl;
}

// 7. Проверка, является ли число степенью двойки
bool isPowerOfTwo(int n) {
    // Число > 0 и у него ровно один бит равен 1 (например, 4 (100) & 3 (011) == 0)
    return (n > 0) && ((n & (n - 1)) == 0);
}

// 8. Получение индекса младшего установленного (1) бита числа
int getLowestSetBitIndex(int n) {
    if (n == 0) return -1; // у нуля нет установленных битов
    int index = 0;
    while ((n & 1) == 0) {
        n >>= 1;
        index++;
    }
    return index;
}

// 9. Функция, которая обнуляет младший установленный бит у числа
int clearLowestSetBit(int n) {
    // Классический трюк: n & (n - 1) сбрасывает самый правый включенный бит
    return n & (n - 1);
}

int main() {
    // Примеры проверки работы функций:
    int num = 13; // В двоичной системе (4-битной): 1101 (в int гораздо больше нулей слева)
    
    cout << "--- Завдання 1 ---" << endl;
    printBits(num);
    
    cout << "\n--- Завдання 2 ---" << endl;
    cout << "Чи число " << num << " парне? " << (isEven(num) ? "Так" : "Ні") << endl;
    
    cout << "\n--- Завдання 3 (Очистити біт з індексом 2) ---" << endl;
    int res3 = clearBit(num, 2); // 13 (1101) -> 9 (1001), так как бит под индексом 2 стал 0
    printBits(res3);
    
    cout << "\n--- Завдання 4 (Встановити біт з індексом 1 в 1) ---" << endl;
    int res4 = setBit(num, 1); // 13 (1101) -> 15 (1111)
    printBits(res4);
    
    cout << "\n--- Завдання 5 (Інвертувати біт з індексом 0) ---" << endl;
    int res5 = toggleBit(num, 0); // 13 (1101 -> последний бит был 1, станет 0) -> 12 (1100)
    printBits(res5);
    
    cout << "\n--- Завдання 6 ---" << endl;
    countBits(num);
    
    cout << "\n--- Завдання 7 ---" << endl;
    int testPow = 16;
    cout << "Чи число " << testPow << " є степенем двійки? " << (isPowerOfTwo(testPow) ? "Так" : "Ні") << endl;
    
    cout << "\n--- Завдання 8 ---" << endl;
    cout << "Індекс молодшого встановленого біта числа " << num << " = " << getLowestSetBitIndex(num) << endl;
    
    cout << "\n--- Завдання 9 ---" << endl;
    int res9 = clearLowestSetBit(num); // Сбросит крайний правый бит
    cout << "Число після обнулення молодшого встановленого біта:" << endl;
    printBits(res9);

    return 0;
}